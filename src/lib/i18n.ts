export function useI18n() {
  const [store] = useStore();
  const lang = (store.language as LanguageCode) || "PT";
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.PT;

  const t = (key: TranslationKey, fallback?: string): string => {
    return dict[key] || TRANSLATIONS.PT[key] || fallback || key;
  };

  const formatPrice = (valAOA: number): string => {
    return formatCurrency(valAOA, store.currency || "AOA");
  };

  return { t, lang, currency: store.currency || "AOA", formatPrice };
}
